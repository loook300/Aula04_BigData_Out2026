pontos = int (input ('Informe os Pontos : '))

if pontos >= 100:
    pontos = pontos + 10 
    print(f'Excelente voce tem {pontos} agora ! ')

elif pontos >= 50 :
    pontos = pontos + 5
    print(f'Bom desempenho você tem {pontos} agora ! ')

else :
    print(f'Não desanime , você está começando. Seus Pontos ')


